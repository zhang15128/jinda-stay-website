function renderOtaLinks(dictionary, language) {
  guideOtaLinks.innerHTML = "";
  let linkCount = 0;
  window.JINDA_DATA.otaPlatforms.forEach((platform) => {
    const href = activeProperty.otaLinks?.[platform.id];
    if (!href) {
      return;
    }

    const link = document.createElement("a");
    link.href = buildOtaUrl(href, activeProperty.id);
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.textContent = `${dictionary.reserveOn} ${getLocalizedName(platform, language)}`;
    guideOtaLinks.append(link);
    linkCount += 1;
  });

  return linkCount;
}

function buildOtaUrl(baseUrl, propertyId) {
  const url = new URL(baseUrl, window.location.href);
  url.searchParams.set("property", propertyId);
  return url.toString();
}

function updatePropertyUrl(propertyId, language) {
  const nextParams = new URLSearchParams(window.location.search);
  nextParams.set("property", propertyId);
  nextParams.set("lang", language);
  window.history.replaceState(null, "", `${window.location.pathname}?${nextParams.toString()}`);
}

function getPropertyName(property, language) {
  return property.names?.[language] || property.name;
}

function getLocalizedName(item, language) {
  if (typeof item === "string") {
    return item;
  }

  return item.names?.[language] || item.name;
}

function getGoogleMapsUrl(property) {
  if (property.mapCid) {
    return `https://www.google.com/maps?cid=${property.mapCid}`;
  }

  return `https://www.google.com/maps?q=${encodeURIComponent(property.mapQuery)}`;
}

