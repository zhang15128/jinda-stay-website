const params = new URLSearchParams(window.location.search);
let activeProperty = properties.find((property) => property.id === params.get("property")) || properties[0];
let activeDemoMode = "lobby";
let demoTimers = [];

function getLanguage() {
  const requestedLanguage = params.get("lang") || localStorage.getItem("jindaLanguage") || "ja";
  return guideTranslations[requestedLanguage] ? requestedLanguage : "ja";
}

function setGuideLanguage(language) {
  const resolvedLanguage = guideTranslations[language] ? language : "ja";
  const dictionary = guideTranslations[resolvedLanguage];
  localStorage.setItem("jindaLanguage", resolvedLanguage);
  languageSelect.value = resolvedLanguage;
  syncLanguagePicker(resolvedLanguage);
  document.documentElement.lang =
    resolvedLanguage === "zhHant" ? "zh-Hant" : resolvedLanguage === "zhHans" ? "zh-CN" : resolvedLanguage;

  document.querySelectorAll("[data-guide-i18n]").forEach((node) => {
    const key = node.dataset.guideI18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  renderSwitcher(resolvedLanguage);
  renderGuide(resolvedLanguage);
  updatePropertyUrl(activeProperty.id, resolvedLanguage);
}

function syncLanguagePicker(language) {
  const selectedOption = languageSelect.querySelector(`option[value="${language}"]`);
  languageCurrent.textContent = selectedOption?.textContent || language;
  languageOptions.forEach((option) => {
    option.setAttribute("aria-selected", String(option.dataset.languageOption === language));
  });
}

function setLanguageMenuOpen(isOpen) {
  languageWrap.classList.toggle("is-open", isOpen);
  languageTrigger.setAttribute("aria-expanded", String(isOpen));
}

function renderSwitcher(language = getLanguage()) {
  propertySwitcher.innerHTML = "";
  properties.forEach((property) => {
    const button = document.createElement("button");
    button.type = "button";
    button.textContent = getPropertyName(property, language);
    button.dataset.propertyId = property.id;
    button.setAttribute("aria-pressed", String(property.id === activeProperty.id));
    button.addEventListener("click", () => {
      activeProperty = property;
      updatePropertyUrl(property.id, languageSelect.value);
      renderSwitcher(languageSelect.value);
      renderGuide(languageSelect.value);
    });
    propertySwitcher.append(button);
  });
}

function renderGuide(language) {
  const dictionary = guideTranslations[language] || guideTranslations.ja;
  const steps = dictionary.genericSteps;

  guidePropertyName.textContent = getPropertyName(activeProperty, language);
  guideAddress.textContent = activeProperty.address;
  const mapUrl = getGoogleMapsUrl(activeProperty);
  guideMap.src = `${mapUrl}&output=embed`;
  guideMapLink.href = mapUrl;
  if (activeProperty.videoSrc) {
    guideVideo.poster = activeProperty.videoPoster;
    guideVideo.src = activeProperty.videoSrc;
    guideVideo.controls = true;
    guideVideoCard.classList.remove("is-unavailable");
  } else {
    guideVideo.removeAttribute("src");
    guideVideo.removeAttribute("poster");
    guideVideo.controls = false;
    guideVideo.load();
    guideVideoCard.classList.add("is-unavailable");
  }
  guideImage.src = activeProperty.guideImage;
  guideImage.alt = `${getPropertyName(activeProperty, language)} ${dictionary.imageLabel}`;
  renderOtaLinks(dictionary, language);

  guideSteps.innerHTML = "";
  steps.forEach((step) => {
    const item = document.createElement("li");
    item.textContent = step;
    guideSteps.append(item);
  });

  nearbyList.innerHTML = "";
  activeProperty.facilities.forEach((facility) => {
    const item = document.createElement("span");
    item.textContent = getLocalizedName(facility, language);
    nearbyList.append(item);
  });

  renderEntryDemo(dictionary);
}

function renderEntryDemo(dictionary) {
  const isAvailable = Boolean(activeProperty.entryDemo);
  entryDemoSection.hidden = !isAvailable;

  if (!isAvailable) {
    entryDemoStage.classList.remove("is-playing");
    return;
  }

  demoModeSwitch.setAttribute("aria-label", dictionary.entryDemoTitle);

  demoModeButtons.forEach((button) => {
    const isActive = button.dataset.demoMode === activeDemoMode;
    button.setAttribute("aria-selected", String(isActive));
    button.tabIndex = isActive ? 0 : -1;
  });
  demoScenes.forEach((scene) => {
    scene.hidden = scene.dataset.demoScene !== activeDemoMode;
  });
  demoSampleCode.textContent = "1234";
  demoCorrection.hidden = activeDemoMode !== "room";
  roomWakeBar.textContent = dictionary.demoRoomWakeBar;

  demoStepList.innerHTML = "";
  const steps = activeDemoMode === "lobby" ? dictionary.lobbyDemoSteps : dictionary.roomDemoSteps;
  steps.forEach((step) => {
    const item = document.createElement("li");
    item.textContent = step;
    demoStepList.append(item);
  });

  playEntryDemo();
}

function setDemoMode(mode) {
  if (!demoScenes.some((scene) => scene.dataset.demoScene === mode)) {
    return;
  }

  activeDemoMode = mode;
  renderEntryDemo(guideTranslations[languageSelect.value] || guideTranslations.ja);
}

function playEntryDemo() {
  demoTimers.forEach((timer) => window.clearTimeout(timer));
  demoTimers = [];

  entryDemoStage.classList.remove("is-playing");
  void entryDemoStage.offsetWidth;
  resetDemoVisuals();
  entryDemoStage.classList.add("is-playing");

  const dictionary = guideTranslations[languageSelect.value] || guideTranslations.ja;
  demoLobbyPhase.textContent = dictionary.demoLobbyTouch;
  demoRoomPhase.textContent = dictionary.demoRoomWake;

  const schedule = (delay, callback) => {
    demoTimers.push(window.setTimeout(callback, delay));
  };

  if (activeDemoMode === "lobby") {
    schedule(260, () => {
      lobbyScreen.classList.add("is-touched");
      demoLobbyPhase.textContent = dictionary.demoLobbyTouch;
    });
    schedule(900, () => {
      tapDemoKey("lobby-call");
      demoLobbyPhase.textContent = dictionary.demoLobbyCall;
    });
    ["lobby-1", "lobby-2", "lobby-3", "lobby-4"].forEach((key, index) => {
      schedule(1400 + index * 360, () => {
        tapDemoKey(key);
        revealDemoCode("lobby", index + 1);
      });
    });
    schedule(3150, () => {
      demoLobbyPhase.textContent = dictionary.demoLobbyOpen;
      demoUnlockLights[0].classList.add("is-unlocked");
      lobbyDoor.classList.add("is-open");
      entryDemoStage.classList.add("is-complete");
    });
    return;
  }

  schedule(280, () => tapDemoKey("room-wake"));
  schedule(620, () => {
    roomWakeBar.classList.remove("is-tapped");
    void roomWakeBar.offsetWidth;
    roomWakeBar.classList.add("is-tapped");
  });
  schedule(1020, () => {
    roomRandomText.classList.add("is-visible");
    demoRoomPhase.textContent = dictionary.demoRandom;
  });
  schedule(1770, () => {
    roomRandomText.classList.remove("is-visible");
    demoRoomPhase.textContent = dictionary.demoRoomReady;
  });
  ["room-1", "room-2", "room-3", "room-4"].forEach((key, index) => {
    schedule(2250 + index * 360, () => {
      tapDemoKey(key);
      revealDemoCode("room", index + 1);
    });
  });
  schedule(3920, () => {
    tapDemoKey("room-confirm");
    demoUnlockLights[1].classList.add("is-unlocked");
  });
  schedule(4390, () => roomHandle.classList.add("is-down"));
  schedule(4860, () => {
    roomDoorLeaf.classList.add("is-open");
    entryDemoStage.classList.add("is-complete");
  });
}

function resetDemoVisuals() {
  entryDemoStage.classList.remove("is-complete");
  lobbyScreen.classList.remove("is-touched");
  lobbyDoor.classList.remove("is-open");
  roomWakeBar.classList.remove("is-tapped");
  roomRandomText.classList.remove("is-visible");
  roomDoorLeaf.classList.remove("is-open");
  roomHandle.classList.remove("is-down");
  demoUnlockLights.forEach((light) => light.classList.remove("is-unlocked"));
  demoKeyElements.forEach((key) => key.classList.remove("is-tapped"));
  demoCodeDisplays.forEach((display) => {
    display.querySelectorAll("i").forEach((digit) => digit.classList.remove("is-visible"));
  });
}

function tapDemoKey(keyId) {
  const key = document.querySelector(`[data-demo-key="${keyId}"]`);
  key?.classList.add("is-tapped");
}

function revealDemoCode(codeType, digitCount) {
  const display = document.querySelector(`[data-demo-code="${codeType}"]`);
  display?.querySelectorAll("i").forEach((digit, index) => {
    digit.classList.toggle("is-visible", index < digitCount);
  });
}

function renderOtaLinks(dictionary, language) {
  guideOtaLinks.innerHTML = "";
  window.JINDA_DATA.otaPlatforms.forEach((platform) => {
    const href = activeProperty.otaLinks?.[platform.id];
    if (!href) {
      return;
    }

    const link = document.createElement("a");
    link.href = buildOtaUrl(href, activeProperty.id);
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.textContent = `${dictionary.reserveOn} ${getLocalizedName(platform, language)}`;
    guideOtaLinks.append(link);
  });
}

function buildOtaUrl(baseUrl, propertyId) {
  const url = new URL(baseUrl, window.location.href);
  url.searchParams.set("property", propertyId);
  return url.toString();
}

function updatePropertyUrl(propertyId, language) {
  const nextParams = new URLSearchParams(window.location.search);
  nextParams.set("property", propertyId);
  nextParams.set("lang", language);
  window.history.replaceState(null, "", `${window.location.pathname}?${nextParams.toString()}`);
}

function getPropertyName(property, language) {
  return property.names?.[language] || property.name;
}

function getLocalizedName(item, language) {
  if (typeof item === "string") {
    return item;
  }

  return item.names?.[language] || item.name;
}

function getGoogleMapsUrl(property) {
  if (property.mapCid) {
    return `https://www.google.com/maps?cid=${property.mapCid}`;
  }

  return `https://www.google.com/maps?q=${encodeURIComponent(property.mapQuery)}`;
}

