const availabilityButton = document.querySelector(".availability-button");
const bookingStatus = document.querySelector("#bookingStatus");
const properties = window.JINDA_DATA.properties;

let activeSlide = 0;

function getSavedLanguage() {
  const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
  const savedLanguage = requestedLanguage || localStorage.getItem("jindaLanguage") || "ja";
  return translations[savedLanguage] ? savedLanguage : "ja";
}

function setLanguage(language) {
  const resolvedLanguage = translations[language] ? language : "ja";
  const dictionary = translations[resolvedLanguage];
  localStorage.setItem("jindaLanguage", resolvedLanguage);
  languageSelect.value = resolvedLanguage;
  syncLanguagePicker(resolvedLanguage);
  document.documentElement.lang =
    resolvedLanguage === "zhHant" ? "zh-Hant" : resolvedLanguage === "zhHans" ? "zh-CN" : resolvedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  populateDestinations(resolvedLanguage);
  renderPropertyEntryList(resolvedLanguage);
}

function syncLanguagePicker(language) {
  const selectedOption = languageSelect.querySelector(`option[value="${language}"]`);
  languageCurrent.textContent = selectedOption?.textContent || language;
  languageOptions.forEach((option) => {
    const isSelected = option.dataset.languageOption === language;
    option.setAttribute("aria-selected", String(isSelected));
  });
}

function setLanguageMenuOpen(isOpen) {
  languageWrap.classList.toggle("is-open", isOpen);
  languageTrigger.setAttribute("aria-expanded", String(isOpen));
}

function populateDestinations(language = getSavedLanguage()) {
  if (!destinationInput) {
    return;
  }

  const selectedProperty = destinationInput.value || properties[0]?.id;
  destinationInput.innerHTML = "";
  properties.forEach((property) => {
    const option = document.createElement("option");
    option.value = property.id;
    option.textContent = getPropertyName(property, language);
    destinationInput.append(option);
  });
  if (properties.some((property) => property.id === selectedProperty)) {
    destinationInput.value = selectedProperty;
  }
}

function getPropertyName(property, language) {
  return property.names?.[language] || property.name;
}

function renderPropertyEntryList(language = getSavedLanguage()) {
  if (!propertyEntryList) {
    return;
  }

  const dictionary = translations[language] || translations.ja;
  propertyEntryList.innerHTML = "";
  properties.forEach((property) => {
    const link = document.createElement("a");
    link.className = "property-entry-card";
    link.href = `./guide.html?property=${encodeURIComponent(property.id)}&lang=${encodeURIComponent(language)}`;
    link.innerHTML = `
      <figure class="property-entry-media">
        <img src="${property.cardImage || property.guideImage}" alt="" loading="lazy" />
      </figure>
      <div class="property-entry-copy">
        <span>${property.area}</span>
        <strong>${getPropertyName(property, language)}</strong>
        <small>${property.address}</small>
        <em><span>${dictionary.propertyEntryCta}</span><span aria-hidden="true">→</span></em>
      </div>
    `;
    propertyEntryList.append(link);
  });
}

function addDays(dateString, days) {
  const [year, month, day] = dateString.split("-").map(Number);
  const date = new Date(year, month - 1, day + days);
  const nextYear = date.getFullYear();
  const nextMonth = String(date.getMonth() + 1).padStart(2, "0");
  const nextDay = String(date.getDate()).padStart(2, "0");
  return `${nextYear}-${nextMonth}-${nextDay}`;
}

function goToSlide(index) {
  slides[activeSlide].classList.remove("is-active");
  activeSlide = (index + slides.length) % slides.length;
  slides[activeSlide].classList.add("is-active");
  currentSlide.textContent = String(activeSlide + 1).padStart(2, "0");
}

function setMenuOpen(isOpen) {
  menuDrawer.classList.toggle("is-open", isOpen);
  menuDrawer.setAttribute("aria-hidden", String(!isOpen));
  document.body.classList.toggle("menu-open", isOpen);
  menuButtons.forEach((button) => button.setAttribute("aria-expanded", String(isOpen)));
}

function showBookingError(message) {
  bookingStatus.textContent = message;
  bookingStatus.classList.add("has-message");
}

function searchAvailability() {
  const language = languageSelect.value;
  const dictionary = translations[language] || translations.ja;
  const propertyId = destinationInput.value;
  const checkIn = checkInInput.value;
  const stayUntil = stayUntilInput.value;

  if (!checkIn || !stayUntil || stayUntil < checkIn) {
    showBookingError(dictionary.invalidDate);
    return;
  }

  const checkout = addDays(stayUntil, 1);
  const params = new URLSearchParams({
    property: propertyId,
    checkin: checkIn,
    until: stayUntil,
    checkout,
    lang: language,
  });

  window.location.href = `./rooms.html?${params.toString()}`;
}

function openDatePicker(input) {
  input.focus({ preventScroll: true });

  if (typeof input.showPicker === "function") {
    try {
      input.showPicker();
    } catch {
      input.focus({ preventScroll: true });
    }
    return;
  }

  input.focus({ preventScroll: true });
}

function openSelectPicker(select) {
  select.focus({ preventScroll: true });

  if (typeof select.showPicker === "function") {
    select.showPicker();
    return;
  }

  select.click();
}

